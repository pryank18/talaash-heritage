"""Builds the Heritage desk (news): site/news.html, one page per story
(site/news-<slug>.html) and site/sitemap-news.xml, from content/news/*.json.

News means everything happening in the fields Talaash covers: finds and
excavations, research and publications, museums and exhibitions, conferences
and lectures, opportunities (jobs, fellowships, courses, calls, exam notices)
and sites, policy and conservation. Every story is written in our own words
and lists its sources. Rules: content/news/README.md.

Run:  python3 tools/build_news.py           (build)
      python3 tools/build_news.py --check   (validate only, exit 1 on any problem)
      python3 tools/build_news.py --coverage  (stories per field over the last 14 days)
"""
import datetime, html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
NEWS_DIR = os.path.join(ROOT, "content", "news")
SITE_URL = "https://talaash-heritage.pages.dev/"
EMAIL = "talaashheritage@gmail.com"
MARK = "<!-- generated by tools/build_news.py: edit content/news/<slug>.json, not this file -->"

CATEGORIES = {
    "finds": ("Finds and excavations", "Finds"),
    "research": ("Research and publications", "Research"),
    "exhibitions": ("Museums and exhibitions", "Exhibitions"),
    "events": ("Conferences, lectures and seminars", "Events"),
    "opportunities": ("Jobs, fellowships, courses and calls", "Opportunities"),
    "policy": ("Sites, policy and conservation", "Sites and policy"),
}
# The seven fields in the name TALAASHH. Every one gets its own place on the
# desk, and --coverage shows which ones are thin over the last 14 days.
FIELDS = {
    "archaeology": ("Archaeology", "what-is-archaeology"),
    "linguistics": ("Linguistics and scripts", "classical-languages-of-india"),
    "anthropology": ("Anthropology", "what-is-anthropology"),
    "arts": ("Arts, crafts and performance", "classical-dances-of-india"),
    "sanskrit": ("Sanskrit and classical texts", "what-is-sanskrit"),
    "history": ("History", "indian-history-timeline"),
    "heritage": ("Heritage, museums and conservation", "what-is-cultural-heritage"),
}
COVERAGE_DAYS = 14
COVERAGE_TARGET = 2  # stories per field per 14 days
STATUS = {"published", "draft", "withdrawn"}
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

h = lambda x: html.escape(str(x), quote=True)


def fmt(d):
    return datetime.date.fromisoformat(d).strftime("%-d %B %Y")


def fields_of(s):
    return [s["field"]] + list(s.get("also_fields", []))


def validate(s, fname):
    errs = []
    need = ["slug", "title", "dek", "body", "category", "field", "published", "sources", "status"]
    for k in need:
        if k not in s:
            errs.append(f"missing {k}")
    if errs:
        return errs
    if not SLUG_RE.match(s["slug"]) or len(s["slug"]) > 90:
        errs.append("slug must be lowercase words joined by hyphens")
    if fname != s["slug"] + ".json":
        errs.append("file name must be <slug>.json")
    if not 8 <= len(s["title"]) <= 160:
        errs.append("title must be 8 to 160 characters")
    if not 20 <= len(s["dek"]) <= 400:
        errs.append("dek must be 20 to 400 characters")
    if not isinstance(s["body"], list) or not (2 <= len(s["body"]) <= 8) or any(len(p) < 20 for p in s["body"]):
        errs.append("body must be a list of 2 to 8 paragraphs")
    if s["category"] not in CATEGORIES:
        errs.append("category must be one of " + ", ".join(CATEGORIES))
    if s["field"] not in FIELDS:
        errs.append("field must be one of " + ", ".join(FIELDS))
    also = s.get("also_fields", [])
    if not isinstance(also, list) or any(f not in FIELDS or f == s["field"] for f in also) or len(also) != len(set(also)) or len(also) > 2:
        errs.append("also_fields: up to 2 other fields from the seven, not repeating field")
    if s["status"] not in STATUS:
        errs.append("status must be published, draft or withdrawn")
    for k in ("published", "updated", "event_start", "event_end", "deadline"):
        if s.get(k) and not DATE_RE.match(s[k]):
            errs.append(f"{k} must be YYYY-MM-DD")
    if s["status"] == "withdrawn" and not s.get("correction"):
        errs.append("a withdrawn story needs a correction note")
    if not isinstance(s["sources"], list) or not s["sources"]:
        errs.append("at least one source")
    else:
        for src in s["sources"]:
            if not src.get("url", "").startswith("https://") or not src.get("title") or not src.get("publisher"):
                errs.append("each source needs title, publisher and an https url")
    text = " ".join([s["title"], s["dek"]] + list(s["body"]))
    if "http" in text:
        errs.append("no links in the story text; put them in sources")
    return errs


def load():
    stories, problems = [], []
    if not os.path.isdir(NEWS_DIR):
        return stories, problems
    for f in sorted(os.listdir(NEWS_DIR)):
        if not f.endswith(".json"):
            continue
        try:
            s = json.load(open(os.path.join(NEWS_DIR, f), encoding="utf-8"))
        except Exception as e:
            problems.append(f"{f}: not valid JSON ({e})")
            continue
        errs = validate(s, f)
        if errs:
            problems += [f"{f}: {e}" for e in errs]
            continue
        stories.append(s)
    stories.sort(key=lambda s: (s["published"], s["slug"]), reverse=True)
    return stories, problems


