"""Make one self-contained file per payment function, for pasting into the
Supabase dashboard editor (Edge Functions > Deploy a new function > Via editor),
which cannot reach the shared file. Run after editing anything in
supabase/functions:  python3 tools/bundle_functions.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "supabase"
shared = (ROOT / "functions/_shared/razorpay.ts").read_text()
shared = re.sub(r"^export ", "", shared, flags=re.M)
out = ROOT / "paste"
out.mkdir(exist_ok=True)
for name in ("create-order", "verify-payment", "razorpay-webhook"):
    src = (ROOT / f"functions/{name}/index.ts").read_text()
    head, sep, body = src.partition("\n\n")  # leading comment block
    body = re.sub(r'^import \{[^}]*\} from "\.\./_shared/razorpay\.ts";\n', "", body, flags=re.M)
    text = (
        f"// GENERATED by tools/bundle_functions.py from supabase/functions/{name}. Edit there.\n"
        f"// Paste this whole file as the function named \"{name}\".\n"
        f"{head}\n\n// ---- shared ----\n{shared}\n// ---- {name} ----\n{body}"
    )
    (out / f"{name}.ts").write_text(text)
    print("wrote", out / f"{name}.ts")
