def main():
    models, progs, guides = load()
    pages = [m["page"] for m in models]
    if len(set(pages)) != len(pages):
        fail("two models share a page name")
    for m in models:
        check(m, progs, guides)
    for m in models:
        open(os.path.join(SITE, m["page"] + ".html"), "w", encoding="utf-8").write(page(m, models, progs, guides))
        print("wrote", m["page"])
    sm = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "".join(
        f"  <url><loc>{SITE_URL}{m['page']}.html</loc><lastmod>{m.get('updated', m['published'])}</lastmod></url>\n" for m in models) + "</urlset>\n"
    open(os.path.join(SITE, "sitemap-3d.xml"), "w", encoding="utf-8").write(sm)


if __name__ == "__main__":
    main()
