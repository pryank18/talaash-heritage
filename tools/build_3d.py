"""Builds the interactive 3D model pages, site/3d-<page>.html, and site/sitemap-3d.xml
from content/models3d.json. The scene for each page is site/assets/js/3d/<script>.js
(three.js is vendored in site/assets/js/vendor/three; no CDN).

Every page carries the Talaash and archaeologywala logos in the viewer corner, the
reconstruction label, the evidence tag on every labelled part and in the facts table,
a "Plan a visit" block, the series line with both handles, and its sources.

Run:  python3 tools/build_3d.py   (then python3 tools/clean_urls.py)
"""
import html, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
SITE_URL = "https://talaash-heritage.pages.dev/"
MARK = "<!-- generated by tools/build_3d.py: edit content/models3d.json, not this file -->"
TAGS = ["Measured", "Documented", "Comparative", "Hypothetical", "Reconstructed", "Estimated", "Illustrative"]
h = lambda x: html.escape(str(x), quote=True)


def load():
    return json.load(open(os.path.join(ROOT, "content", "models3d.json"), encoding="utf-8"))["models"]


def tag(t):
    assert t in TAGS, t
    return f'<span class="m3d-tag tag-{t.lower()}">{t}</span>'


def page(m):
    url = SITE_URL + m["page"] + ".html"
    img = SITE_URL + m["still"]
    ld = json.dumps({"@context": "https://schema.org", "@graph": [{
        "@type": "Article", "headline": m["h1"], "description": m["description"], "mainEntityOfPage": url, "url": url,
        "image": img, "datePublished": m["published"], "dateModified": m["published"], "inLanguage": "en-IN",
        "author": {"@type": "Person", "@id": SITE_URL + "archaeologywala.html#person", "name": "Pryank Wadhera", "alternateName": "archaeologywala",
                   "url": SITE_URL + "archaeologywala.html", "sameAs": ["https://www.instagram.com/archaeologywala/"]},
        "publisher": {"@type": "Organization", "name": "Talaash Heritage", "url": SITE_URL,
                      "logo": {"@type": "ImageObject", "url": SITE_URL + "assets/img/logo-192.png"}}},
        {"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Learn", "item": SITE_URL + "learn.html"},
            {"@type": "ListItem", "position": 2, "name": m["crumb"][1], "item": SITE_URL + m["crumb"][0] + ".html"},
            {"@type": "ListItem", "position": 3, "name": m["og_title"], "item": url}]}]}, ensure_ascii=False).replace("</", "<\\/")
    facts = "".join(f'<tr><th scope="row">{h(k)}</th><td>{tag(t)}{h(v)}</td></tr>' for k, v, t in m["facts"])
    key = "".join(f"<li>{tag(t)}</li>" for t in TAGS if any(f[2] == t for f in m["facts"]))
    body = "".join(f"<p>{h(p)}</p>" for p in m["body"])
    links = "".join(f'<li><a href="{h(p)}.html">{h(t)}</a></li>' for p, t in m["visit_links"])
    sources = "".join(f"<li>{s}</li>" for s in m["sources"])
    return f"""<!doctype html>
{MARK}
<html lang="en-IN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<script src="assets/js/theme.js"></script>
<title>{h(m["title"])}</title>
<meta name="description" content="{h(m["description"])}">
<link rel="canonical" href="{h(url)}">
<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">
<meta property="og:type" content="article">
<meta property="og:site_name" content="Talaash Heritage">
<meta property="og:locale" content="en_IN">
<meta property="og:url" content="{h(url)}">
<meta property="og:title" content="{h(m["og_title"])}">
<meta property="og:description" content="{h(m["og_description"])}">
<meta property="og:image" content="{h(img)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{h(m["og_title"])}">
<meta name="twitter:description" content="{h(m["og_description"])}">
<meta name="twitter:image" content="{h(img)}">
<meta name="theme-color" content="#2a2926">
<link rel="icon" href="assets/img/favicon-64.png" type="image/png">
<link rel="apple-touch-icon" href="assets/img/apple-touch-icon.png">
<link rel="manifest" href="manifest.webmanifest">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Talaash">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Sans:ital,wght@0,400;0,500;0,600;0,700;1,400&family=Noto+Sans+Devanagari:wght@400;600&family=Tiro+Devanagari+Sanskrit:ital@0;1&display=swap">
<link rel="stylesheet" href="assets/css/styles.css">
<link rel="stylesheet" href="assets/css/model3d.css">
<script type="application/ld+json">{ld}</script>
</head>
<body data-gate="open" data-english-only="1" class="guide-page m3d-page">
<div id="site-header"></div>
<main id="main">
<div class="wrap guide">
  <p class="crumbs"><a href="learn.html">Learn</a> / <a href="{h(m["crumb"][0])}.html">{h(m["crumb"][1])}</a> / 3D</p>
  <article class="guide-body">
    <header class="guide-head">
      <p class="guide-eyebrow">{h(m["eyebrow"])} · Interactive 3D</p>
      <h1>{h(m["h1"])}</h1>
      <p class="guide-lede">{m["lede"]}</p>
    </header>
    <div class="m3d-wrap">
      <div class="m3d-stage" id="m3d-stage">
        <img class="m3d-still" src="{h(m["still"])}" alt="Still view of the 3D model: {h(m["short"])}" width="1600" height="900">
        <div class="m3d-labels" aria-hidden="true"></div>
        <p class="m3d-hint">Drag to turn · pinch or scroll to zoom</p>
        <div class="m3d-brand"><img src="assets/img/logo-192.webp" alt="Talaash Heritage" width="40" height="40"><img src="assets/img/archaeologywala-logo.webp" alt="archaeologywala" width="40" height="40"></div>
        <p class="m3d-recon">{h(m["label"])}</p>
      </div>
      <p class="m3d-note-nowebgl small">Your browser cannot show 3D here, so this is a still view of the model. The facts are below.</p>
      <div class="m3d-toggles" aria-label="Model controls"></div>
      <ul class="m3d-key" aria-label="Evidence tags used on this model">{key}</ul>
    </div>
    <div class="doc guide-text">
      <h2 id="facts">What is measured and what is estimated</h2>
      <table class="m3d-facts">{facts}</table>
      <h2 id="about">About this model</h2>
      {body}
    </div>
    <section class="m3d-visit" aria-labelledby="visit-title">
      <h2 id="visit-title">Plan a visit</h2>
      <p>{h(m["visit"])}</p>
      <ul>{links}</ul>
      <p><a class="btn btn-primary" href="{h(m["sells"])}.html">See {h(dict(m["visit_links"])[m["sells"]].split(" (")[0])}</a></p>
    </section>
    <p class="m3d-follow"><img src="assets/img/logo-192.webp" alt="" width="34" height="34"><img src="assets/img/archaeologywala-logo.webp" alt="" width="34" height="34"><span>Follow the series: <a href="https://www.instagram.com/talaashheritage/" rel="noopener" target="_blank">@talaashheritage</a> and <a href="https://www.instagram.com/archaeologywala/" rel="noopener" target="_blank">@archaeologywala</a></span></p>
    <section aria-labelledby="src-title">
      <h2 id="src-title">Sources</h2>
      <ol class="m3d-sources small">{sources}</ol>
      <p class="small muted">Model built with three.js by Talaash Heritage. Published {h(m["published"])}.</p>
    </section>
  </article>
</div>
</main>
<div id="site-footer"></div>
<script type="module" src="assets/js/layout.js"></script>
<script type="module" src="assets/js/3d/{h(m["script"])}.js"></script>
</body>
</html>
"""


def main():
    models = load()
    for m in models:
        open(os.path.join(SITE, m["page"] + ".html"), "w", encoding="utf-8").write(page(m))
        print("wrote", m["page"])
    sm = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "".join(
        f"  <url><loc>{SITE_URL}{m['page']}.html</loc><lastmod>{m['published']}</lastmod></url>\n" for m in models) + "</urlset>\n"
    open(os.path.join(SITE, "sitemap-3d.xml"), "w", encoding="utf-8").write(sm)


if __name__ == "__main__":
    main()
