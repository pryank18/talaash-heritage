"""Builds the interactive 3D model pages, site/3d-<page>.html, and site/sitemap-3d.xml
from content/models3d.json. The scene for each page is site/assets/js/3d/<script>.js
(three.js is vendored in site/assets/js/vendor/three; no CDN). Follow docs/3D-SOP.md.

Every page carries: both logos (Talaash and archaeologywala) in the viewer corner, the
reconstruction label, an evidence tag on every labelled part and in the facts table,
metric and imperial units, a "Plan a visit" block with a WhatsApp request, programme
cards, "More in 3D" (every other model), "Read next" (the guides), the series line with
both handles, the sources, Article and BreadcrumbList JSON-LD.

The build stops with an error if a linked page, image or scene script is missing, if a
tag is not one of the seven, or if a required field is empty.

Run:  python3 tools/build_3d.py   (then python3 tools/clean_urls.py)
"""
import datetime, html, json, os, sys
from urllib.parse import quote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
SITE_URL = "https://talaash-heritage.pages.dev/"
WA_NUMBER = "917397829282"  # CONFIG.whatsappNumber in assets/js/config.js
MARK = "<!-- generated by tools/build_3d.py: edit content/models3d.json, not this file -->"
TAGS = ["Measured", "Documented", "Comparative", "Hypothetical", "Reconstructed", "Estimated", "Illustrative"]
REQUIRED = ["page", "ledger", "script", "app", "still", "label", "title", "h1", "eyebrow", "crumb", "short", "description",
            "og_title", "og_description", "lede", "facts", "body", "visit", "visit_links", "sells", "guides", "programmes",
            "sources", "published"]
h = lambda x: html.escape(str(x), quote=True)
SHARE_ICON = ('<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" '
              'aria-hidden="true" focusable="false"><circle cx="18" cy="5.5" r="2.5"/><circle cx="6" cy="12" r="2.5"/><circle cx="18" cy="18.5" r="2.5"/>'
              '<path d="m8.2 10.8 7.6-4.1M8.2 13.2l7.6 4.1"/></svg>')


def fail(msg):
    sys.exit("build_3d.py: " + msg)


def load():
    models = json.load(open(os.path.join(ROOT, "content", "models3d.json"), encoding="utf-8"))["models"]
    cat = json.load(open(os.path.join(SITE, "data", "catalogue.json"), encoding="utf-8"))
    progs = {p["page"][:-5]: p for p in cat["programmes"] if p.get("is_active")}
    guides = {}
    gdir = os.path.join(ROOT, "content", "guides")
    for f in os.listdir(gdir):
        if f.endswith(".json"):
            g = json.load(open(os.path.join(gdir, f), encoding="utf-8"))
            guides[g["slug"]] = g
    return models, progs, guides


def check(m, progs, guides):
    for k in REQUIRED:
        if not m.get(k):
            fail(f"{m.get('page')}: '{k}' is empty")
    for f in m["facts"]:
        if len(f) != 3 or f[2] not in TAGS:
            fail(f"{m['page']}: fact {f!r} needs [label, text, one of {TAGS}]")
    for path in (m["still"], f"assets/js/3d/{m['script']}.js", f"assets/js/vendor/{m['app']['three']}/three.min.js", "assets/js/3d/dc-lite.js", "assets/img/logo-192.webp", "assets/img/archaeologywala-logo.webp"):
        if not os.path.exists(os.path.join(SITE, path)):
            fail(f"{m['page']}: missing file site/{path}")
    for s in m["guides"]:
        if s not in guides:
            fail(f"{m['page']}: guide '{s}' does not exist")
    for s in m["programmes"]:
        if s not in progs:
            fail(f"{m['page']}: programme '{s}' does not exist or is not active")
    for s, _ in m["visit_links"]:
        if not os.path.exists(os.path.join(SITE, s + ".html")):
            fail(f"{m['page']}: visit link '{s}' does not exist")
    if m["sells"] not in dict(m["visit_links"]):
        fail(f"{m['page']}: 'sells' must be one of the visit links")
    if not os.path.exists(os.path.join(SITE, m["crumb"][0] + ".html")):
        fail(f"{m['page']}: crumb page '{m['crumb'][0]}' does not exist")


def nice_date(iso):
    return datetime.date.fromisoformat(iso).strftime("%-d %B %Y")


def tag(t):
    return f'<span class="m3d-tag tag-{t.lower()}">{t}</span>'


def prog_card(p):
    """Same markup as the programme cards on guides (build_learn.prog_card)."""
    page = p["page"]
    meta = " · ".join(x for x in (p["details"].get("Length"), p["venue"]) if x)
    if p.get("image_small"):
        art = (f'<a class="card-art" href="{h(page)}" tabindex="-1" aria-hidden="true"><img src="{h(p["image_small"])}" '
               f'alt="{h(p["image_alt"])}" width="500" height="375" loading="lazy"{" class=\"fit-contain\"" if p.get("image_fit") == "contain" else ""}></a>')
    elif p.get("image_url"):
        art = (f'<a class="card-art" href="{h(page)}" tabindex="-1" aria-hidden="true"><img src="{h(p["image_url"].replace(".jpg", "-s.jpg"))}" '
               f'alt="{h("Illustration for " + p["title"])}" width="560" height="420" loading="lazy"></a>')
    else:
        art = ""
    kind = f'{p["kind"]} · {p["pricing"]["card"]}' if p.get("pricing") else p["kind"]  # no price unless pricing.SHOW_PRICES
    return (f'<article class="card{"" if art else " card-text"}">{art}<p class="card-type">{h(kind)}</p>'
            f'<h3><a href="{h(page)}">{h(p["title"])}</a></h3><p class="card-meta">{h(meta)}</p>'
            f'<div class="card-foot card-foot-wide"><a class="btn btn-outline btn-small" href="{h(page)}">See the plan</a></div></article>')


def model_card(o):
    return (f'<article class="card m3d-card"><a class="card-art" href="{h(o["page"])}.html" tabindex="-1" aria-hidden="true">'
            f'<img src="{h(o["still"])}" alt="" width="1600" height="900" loading="lazy"></a>'
            f'<p class="card-type">Interactive 3D · {h(o["eyebrow"])}</p><h3><a href="{h(o["page"])}.html">{h(o["short"])}</a></h3>'
            f'<p class="card-meta">{h(o["og_description"])}</p>'
            f'<div class="card-foot card-foot-wide"><a class="btn btn-outline btn-small" href="{h(o["page"])}.html">Open the model</a></div></article>')


def wa(m):
    text = (f'Hello Talaash Heritage, I explored your 3D model of {m["short"]} and would like to visit or learn more.\n\n'
            "Who it is for (school, college, workplace or private group): \nGroup size: \nPreferred dates: \nCity or online: \n\n"
            f"(ref: {m['page']})")
    return f"https://wa.me/{WA_NUMBER}?text={quote(text, safe='')}"


