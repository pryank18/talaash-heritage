#!/usr/bin/env python3
"""Durlabh Sunday: one rare, well-sourced long read a week (rules: docs/UNIVERSE.md, "Durlabh Sunday").

Source: content/durlabh/<NN>-<slug>.json, one file per piece. This script writes
  site/<page>.html          for every piece whose "release" time has passed (IST) and that is not on hold,
  site/durlabh.html         the index of released pieces, newest first,
  site/sitemap-durlabh.xml  released pieces and the index.
A piece whose release time is still ahead is NOT written, so nothing leaks early.
The GitHub Action "Durlabh Sunday: release" runs this every Sunday morning and commits.

Video: the YouTube parts in "youtube" are embedded only when "video_public" is true
(the Sunday review / release task sets it after reading the videos back as public).

Podcast: a piece with an optional "audio" entry {"file": "media/podcast/durlabh-NN-slug.mp3",
"bytes": <size>, "seconds": <length>} gets an audio player on its page and an episode in
site/podcast.xml (the "Durlabh Sunday" podcast feed, submitted once to Spotify and Apple).
The file must exist under site/ with exactly that size. Episodes appear with the page, not earlier.

Usage: python3 tools/build_durlabh.py [--now 2026-11-22T11:05+05:30]   (--now is for tests)
"""
import datetime, json, os, re, sys
from urllib.parse import quote

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_learn as bl  # shared head(), cards, escaping, programme and guide data

h, inline = bl.h, bl.inline
ROOT, SITE, SITE_URL = bl.ROOT, bl.SITE, bl.SITE_URL
SRC = os.path.join(ROOT, "content", "durlabh")
MARK = "<!-- generated by tools/build_durlabh.py: edit content/durlabh/<NN>-<slug>.json, not this file -->"
IST = datetime.timezone(datetime.timedelta(hours=5, minutes=30))
FIELDS = {"archaeology": "Archaeology", "linguistics": "Linguistics", "anthropology": "Anthropology", "arts": "Arts",
          "sanskrit": "Sanskrit", "history": "History", "heritage": "Heritage"}
FOLLOW = [("YouTube", "https://www.youtube.com/@talaashheritage1967"), ("Instagram", "https://www.instagram.com/talaashheritage/"),
          ("Facebook", "https://www.facebook.com/109410924674841"), ("LinkedIn", "https://www.linkedin.com/company/talaashheritage"),
          ("archaeologywala", "https://www.instagram.com/archaeologywala/")]
REQUIRED = ["number", "page", "release", "field", "title", "seo_title", "meta_description", "og_title", "og_description",
            "keywords", "summary", "sections", "faq", "sources", "sells", "related_programmes", "related_guides", "youtube", "video_public"]


def now_ist():
    for a in sys.argv[1:]:
        if a.startswith("--now"):
            return datetime.datetime.fromisoformat(a.split("=", 1)[1] if "=" in a else sys.argv[sys.argv.index(a) + 1])
    return datetime.datetime.now(IST)


def load():
    pieces = []
    for f in sorted(os.listdir(SRC)):
        if not f.endswith(".json"):
            continue
        d = json.load(open(os.path.join(SRC, f), encoding="utf-8"))
        missing = [k for k in REQUIRED if k not in d]
        assert not missing, f"{f}: missing {missing}"
        assert d["page"] == f"durlabh-{d['number']:02d}-" + f.split("-", 1)[1][:-5], f"{f}: page must be durlabh-NN-<slug of file name>"
        assert d["field"] in FIELDS, f"{f}: unknown field {d['field']}"
        assert d["sells"] in {p[:-5] for p in bl.PROGS}, f"{f}: sells {d['sells']} is not a programme page"
        for p in d["related_programmes"]:
            assert p + ".html" in bl.PROGS, f"{f}: {p} is not a programme page"
        for g in d["related_guides"]:
            assert g in bl.GUIDES, f"{f}: {g} is not a guide"
        d["_release"] = datetime.datetime.fromisoformat(d["release"])
        assert d["_release"].tzinfo, f"{f}: release needs a time zone (+05:30)"
        pieces.append(d)
    nums = [d["number"] for d in pieces]
    assert len(nums) == len(set(nums)), "two Durlabh pieces share a number"
    return pieces


def url_of(page):
    return SITE_URL + page


def date_text(dt):
    return dt.astimezone(IST).strftime("%-d %B %Y")


# Every page carries a photograph (Pryank, 12 Nov 2026). A piece may name its own with "image":
# <key in content/media.json>; otherwise it gets the photo for its field. The caption says what it shows.
FIELD_PHOTO = {
    "archaeology": "guide:what-is-archaeology", "linguistics": "guide:brahmi-script", "anthropology": "guide:what-is-ethnography",
    "arts": "guide:folk-dances-of-india-state-wise", "sanskrit": "guide:learn-sanskrit-for-beginners", "history": "red-fort-complex",
    "heritage": "humayuns-tomb",
}
INDEX_PHOTO = "guide:sanskrit-and-indian-knowledge-systems"


def photo_figure(key):
    m = bl.MEDIA[key]
    return (f'<figure class="guide-hero"><img src="{h(m["src"])}" srcset="{h(m["small"])} 500w, {h(m["src"])} 960w" '
            f'sizes="(min-width: 760px) 46rem, 100vw" alt="{h(m["alt"])}" width="960" height="600" fetchpriority="high"{' class="fit-contain"' if m.get("portrait") else ""}>'
            f'<figcaption class="photo-credit">{h(m["alt"])} Photo: <a href="{h(m["page"])}" rel="noopener">{h(m["credit"])}</a>, '
            f'<a href="{h(m["license_url"])}" rel="license noopener">{h(m["license"])}</a>, via {h(m.get("via", "Wikimedia Commons"))}</figcaption></figure>')


def audio_block(d):
    a = d.get("audio")
    if not a:
        return ""
    return (f'<figure class="durlabh-audio"><audio controls preload="none" src="{h(a["file"])}"></audio>'
            f'<figcaption>Listen: {h(d["title"])} ({round(a["seconds"] / 60)} min) · also on the '
            f'<a href="podcast.xml">Durlabh Sunday podcast feed</a></figcaption></figure>')


def check_audio(d):
    a = d.get("audio")
    if not a:
        return
    f = os.path.join(SITE, a["file"])
    assert a["file"].startswith("media/podcast/") and a["file"].endswith(".mp3"), f'{d["page"]}: audio must be media/podcast/*.mp3'
    assert os.path.isfile(f), f'{d["page"]}: audio file {a["file"]} missing'
    assert os.path.getsize(f) == a["bytes"], f'{d["page"]}: audio bytes {a["bytes"]} != file size {os.path.getsize(f)}'
    assert a["seconds"] > 60, f'{d["page"]}: audio seconds looks wrong'


PODCAST_COVER = "assets/img/podcast-durlabh.jpg"
PODCAST_DESC = ("Durlabh means rare, hard to find. Every Sunday Talaash Heritage takes one rare subject from India's past, "
                "in archaeology, linguistics, anthropology, arts, Sanskrit, history or heritage, and studies it properly. "
                "Each episode is the narrated lecture; the full long read, with every source listed, is on talaash-heritage.pages.dev/durlabh.")


def podcast_feed(live, now):
    from email.utils import format_datetime
    from xml.sax.saxutils import escape as x
    eps = [d for d in live if d.get("audio")]
    items = ""
    for d in reversed(eps):
        a, page = d["audio"], url_of(d["page"])
        m, sec = divmod(int(a["seconds"]), 60)
        notes = f'{d["summary"]} Read the full piece with sources: {page}'
        items += f"""  <item>
    <title>{x(d["title"])}</title>
    <description>{x(notes)}</description>
    <link>{x(page)}</link>
    <guid isPermaLink="false">talaash-{x(d["page"])}</guid>
    <pubDate>{format_datetime(d["_release"])}</pubDate>
    <enclosure url="{x(SITE_URL + a["file"])}" length="{a["bytes"]}" type="audio/mpeg"/>
    <itunes:duration>{m // 60:d}:{m % 60:02d}:{sec:02d}</itunes:duration>
    <itunes:episode>{d["number"]}</itunes:episode>
    <itunes:episodeType>full</itunes:episodeType>
    <itunes:explicit>false</itunes:explicit>
  </item>
"""
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
  <title>Durlabh Sunday · Talaash Heritage</title>
  <link>{SITE_URL}durlabh</link>
  <atom:link href="{SITE_URL}podcast.xml" rel="self" type="application/rss+xml"/>
  <language>en-in</language>
  <copyright>© Talaash Heritage</copyright>
  <description>{x(PODCAST_DESC)}</description>
  <itunes:summary>{x(PODCAST_DESC)}</itunes:summary>
  <itunes:author>Talaash Heritage</itunes:author>
  <itunes:owner><itunes:name>Talaash Heritage</itunes:name><itunes:email>talaashheritage@gmail.com</itunes:email></itunes:owner>
  <itunes:image href="{SITE_URL}{PODCAST_COVER}"/>
  <image><url>{SITE_URL}{PODCAST_COVER}</url><title>Durlabh Sunday · Talaash Heritage</title><link>{SITE_URL}durlabh</link></image>
  <itunes:category text="History"/>
  <itunes:category text="Education"/>
  <itunes:explicit>false</itunes:explicit>
  <itunes:type>episodic</itunes:type>
  <lastBuildDate>{format_datetime(now)}</lastBuildDate>
{items}</channel>
</rss>
"""


def video_block(d):
    if not (d["video_public"] and d["youtube"]):
        return ""
    n = len(d["youtube"])
    frames = "".join(
        f'<figure class="durlabh-video"><div class="durlabh-frame"><iframe src="https://www.youtube-nocookie.com/embed/{h(v)}" '
        f'title="{h(d["title"])}, part {i + 1} of {n}" loading="lazy" allow="accelerometer; encrypted-media; gyroscope; picture-in-picture; web-share" '
        f'referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe></div>'
        f'<figcaption>Part {i + 1} of {n} · <a href="https://www.youtube.com/watch?v={h(v)}" rel="noopener" target="_blank">Watch on YouTube</a></figcaption></figure>'
        for i, v in enumerate(d["youtube"]))
    return (f'<section class="durlabh-watch" aria-labelledby="watch-title"><h2 id="watch-title">Watch the lecture</h2>'
            f'<p class="small muted">Narrated with an AI clone of Pryank Wadhera\'s (@archaeologywala) own voice. Slides, sources and subtitles in English.</p>{frames}</section>')


def sources_html(d):
    items = []
    for s in d["sources"]:
        t = h(s["text"])
        items.append(f'<li>{t} <a href="{h(s["url"])}" rel="noopener" target="_blank">Link</a></li>' if s.get("url") else f"<li>{t}</li>")
    return f'<section class="durlabh-sources" aria-labelledby="src-title"><h2 id="src-title">Sources</h2><ol>{"".join(items)}</ol></section>'


def jsonld(d, url):
    org = {"@type": "Organization", "@id": SITE_URL + "#org", "name": "Talaash Heritage", "url": SITE_URL, "logo": SITE_URL + "assets/img/logo-badge.png"}
    graph = [
        {"@type": "Article", "headline": d["title"][:110], "description": d["meta_description"], "mainEntityOfPage": url, "inLanguage": "en-IN",
         "datePublished": d["_release"].isoformat(), "dateModified": d.get("modified", d["_release"].isoformat()), "author": bl.AUTHOR, "publisher": org,
         "keywords": ", ".join(d["keywords"]), "image": SITE_URL + "assets/img/logo-badge.png",
         "isPartOf": {"@type": "CreativeWorkSeries", "name": "Durlabh Sunday", "url": SITE_URL + "durlabh"},
         "citation": [s["text"] for s in d["sources"]]},
        {"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE_URL},
            {"@type": "ListItem", "position": 2, "name": "Durlabh Sunday", "item": SITE_URL + "durlabh"},
            {"@type": "ListItem", "position": 3, "name": d["title"], "item": url}]},
        {"@type": "FAQPage", "mainEntity": [{"@type": "Question", "name": f["q"], "acceptedAnswer": {"@type": "Answer", "text": bl.plain(f["a"])}} for f in d["faq"]]},
    ]
    if d["video_public"] and d["youtube"]:
        for i, v in enumerate(d["youtube"]):
            graph.append({"@type": "VideoObject", "name": f'{d["title"]} (part {i + 1} of {len(d["youtube"])})', "description": d["meta_description"],
                          "thumbnailUrl": f"https://i.ytimg.com/vi/{v}/hqdefault.jpg", "uploadDate": d["_release"].isoformat(),
                          "embedUrl": f"https://www.youtube-nocookie.com/embed/{v}", "contentUrl": f"https://www.youtube.com/watch?v={v}"})
    return json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False).replace("</", "<\\/")


def piece_page(d, prev_next):
    url = url_of(d["page"])
    secs = d["sections"]
    toc = "".join(f'<li><a href="#s{i + 1}">{h(s["h2"])}</a></li>' for i, s in enumerate(secs))
